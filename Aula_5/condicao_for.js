// for(inicialização; condição; incremento ou decremento)

// Cria uma repetição de X vezes.
// Usamos quando sabemos quantas vezes o código vai repetir.
console.log("Contagem decrescente com for:")
for(let i = 5; i >= 0; i--){
    console.log(i)
}

console.log("\n")
console.log("Contagem crescente com while:")
let j = 0
while(j <= 5){
    console.log(j)
    j++
}